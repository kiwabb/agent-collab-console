export type TranslationKey = string;

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "zh-CN" || value === "en-US";
}

function humanizeKey(key: string): string {
  const raw = key.split(".").at(-1) ?? key;
  return raw
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/[_-]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/^./, (c) => c.toUpperCase());
}

export function getDictionaryValue(locale: Locale, key: TranslationKey): string {
  const dictionary = dictionaries[locale] as Record<string, string>;
  const fallbackDictionary = dictionaries[DEFAULT_LOCALE] as Record<string, string>;
  return dictionary[key] ?? fallbackDictionary[key] ?? humanizeKey(key);
}
