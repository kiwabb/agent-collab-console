import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build, version as esbuildVersion } from "esbuild";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(frontendRoot, "..");
const structuredDirectory = "src/features/prototype/structured";
const sourceFiles = [
  "src/features/prototype/runtime/canonical.ts",
  `${structuredDirectory}/structuredPrototypeFreeformGrids.ts`,
  `${structuredDirectory}/structuredPrototypeFreeformMoveEvidence.ts`,
  `${structuredDirectory}/structuredPrototypeFreeformMoveReplay.ts`,
  `${structuredDirectory}/structuredPrototypeGridGeometry.ts`,
  `${structuredDirectory}/structuredPrototypeSnapping.ts`,
  `${structuredDirectory}/structuredPrototypeSnapWorkerProtocol.ts`,
  `${structuredDirectory}/structuredPrototypeSpacingSnapping.ts`,
  `${structuredDirectory}/types.ts`,
  "src/lib/utils.tsx",
  "scripts/prototype-snap-worker.ts",
];
const identityRelativePath = `${structuredDirectory}/structuredPrototypeSnapBuildIdentity.ts`;
const identityPath = resolve(frontendRoot, identityRelativePath);
const outputDirectory = resolve(repositoryRoot, "backend/app/runtime_assets");
const bundlePath = resolve(outputDirectory, "prototype_snap_worker.mjs");
const manifestPath = resolve(outputDirectory, "prototype_snap_worker.manifest.json");
const protocolVersion = "prototype-snap-worker/v1";
const snapSolverVersion = "structured-prototype-freeform-snap/v1";

function sha256(bytes) {
  return `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
}

async function writeAtomically(path, bytes) {
  const temporaryPath = `${path}.tmp-${process.pid}`;
  await writeFile(temporaryPath, bytes);
  await rename(temporaryPath, path);
}

const sources = [];
for (const path of sourceFiles) {
  const bytes = await readFile(resolve(frontendRoot, path));
  sources.push({ path, hash: sha256(bytes), byteSize: bytes.byteLength });
}
const snapSolverSourceHash = sha256(Buffer.from(JSON.stringify(sources), "utf8"));
const identitySource = [
  `export const STRUCTURED_PROTOTYPE_SNAP_SOLVER_VERSION = ${JSON.stringify(snapSolverVersion)};`,
  "",
  "// Regenerated by scripts/build-prototype-snap-worker.mjs from every solver input.",
  "export const STRUCTURED_PROTOTYPE_SNAP_SOURCE_HASH =",
  `  ${JSON.stringify(snapSolverSourceHash)};`,
  "",
].join("\n");
await writeAtomically(identityPath, identitySource);

await mkdir(outputDirectory, { recursive: true });
const buildResult = await build({
  absWorkingDir: frontendRoot,
  bundle: true,
  charset: "utf8",
  entryPoints: ["scripts/prototype-snap-worker.ts"],
  format: "esm",
  legalComments: "none",
  logLevel: "silent",
  metafile: true,
  minify: false,
  outfile: bundlePath,
  platform: "node",
  sourcemap: false,
  target: ["node20"],
  treeShaking: true,
  tsconfig: resolve(frontendRoot, "tsconfig.json"),
  write: false,
});
const output = buildResult.outputFiles?.[0];
if (output === undefined) throw new Error("prototype snap worker build produced no bundle");

const trackedRuntimeSources = new Set([...sourceFiles, identityRelativePath]);
const untrackedRuntimeSources = Object.keys(buildResult.metafile.inputs)
  .filter((path) => path.startsWith("src/") || path.startsWith("scripts/"))
  .filter((path) => !trackedRuntimeSources.has(path));
if (untrackedRuntimeSources.length > 0) {
  throw new Error(
    `prototype snap worker has unhashed runtime sources: ${untrackedRuntimeSources.join(", ")}`,
  );
}

const bundleBytes = Buffer.from(output.contents);
const bundleHash = sha256(bundleBytes);
await writeAtomically(bundlePath, bundleBytes);

const describe = spawnSync(process.execPath, [bundlePath], {
  encoding: "utf8",
  input: JSON.stringify({
    protocolVersion,
    requestId: "build-identity-check",
    action: "describe",
  }),
  maxBuffer: 1024 * 1024,
});
if (describe.status !== 0) {
  throw new Error(`prototype snap worker describe failed: ${describe.stderr.trim()}`);
}
const description = JSON.parse(describe.stdout);
if (
  description.status !== "ok" ||
  description.action !== "describe" ||
  description.protocolVersion !== protocolVersion ||
  description.snapSolverVersion !== snapSolverVersion ||
  description.snapSolverSourceHash !== snapSolverSourceHash ||
  description.result?.protocolVersion !== protocolVersion ||
  description.result?.snapSolverVersion !== snapSolverVersion ||
  description.result?.snapSolverSourceHash !== snapSolverSourceHash
) {
  throw new Error("prototype snap worker identity does not match its build inputs");
}

const manifest = {
  manifestVersion: "prototype-snap-worker-manifest/v1",
  protocolVersion,
  snapSolverVersion,
  snapSolverSourceHash,
  bundleFile: "prototype_snap_worker.mjs",
  bundleHash,
  bundleByteSize: bundleBytes.byteLength,
  buildTool: `esbuild@${esbuildVersion}`,
  target: "node20",
  sources,
};
await writeAtomically(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
